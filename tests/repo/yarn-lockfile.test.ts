/** Conservative Yarn Classic attribution, including peer edges absent from yarn.lock. */
import { strict as assert } from "node:assert";
import { execFileSync, spawnSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, it } from "node:test";
import { analyzeCheckout } from "../../src/analyze.js";
import { analyzeGitDelta } from "../../src/git/git-diff.js";
import { yarnLockAffectedDependencies } from "../../src/repo/yarn-lockfile.js";

const header = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n";
const roots = { consumer: "^1.0.0", host: "^1.0.0" };
function entry(name: string, version = "1.0.0", range = "^1.0.0", extra = ""): string {
  return `${JSON.stringify(`${name}@${range}`)}:\n  version ${JSON.stringify(version)}\n  resolved ${JSON.stringify(`https://registry.yarnpkg.com/${name}/-/${name.split("/").at(-1)}-${version}.tgz#${version === "1.0.0" ? "1" : "2"}111111111111111111111111111111111111111`)}\n${extra}\n`;
}
const lock = (host = "1.0.0") => header + entry("consumer") + entry("host", host);
const manifest = (fields: Record<string, unknown> = {}) => JSON.stringify({ name: "fixture", private: true, type: "module", scripts: { test: "node --test" }, dependencies: roots, ...fields }, null, 2) + "\n";
const files: Record<string, string> = {
  ".gitignore": "node_modules/\n",
  "package.json": manifest(),
  "yarn.lock": lock(),
  "src/host.test.js": `import test from "node:test";\nimport assert from "node:assert/strict";\nimport { value } from "host";\ntest("host returns a string", () => assert.equal(typeof value, "string"));\n`,
  "src/consumer.test.js": `import test from "node:test";\nimport assert from "node:assert/strict";\nimport { value } from "consumer";\ntest("consumer expects the original peer behavior", () => assert.equal(value, "ready"));\n`,
  "src/unrelated.test.js": `import test from "node:test";\nimport assert from "node:assert/strict";\ntest("unrelated", () => assert.equal(2 + 2, 4));\n`,
};
type Files = Record<string, string | undefined>;
function write(dir: string, values: Files): void {
  for (const [path, content] of Object.entries(values)) {
    const full = join(dir, path);
    if (content === undefined) { rmSync(full, { force: true }); continue; }
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, content);
  }
}
function git(dir: string, ...args: string[]): string {
  return execFileSync("git", args, { cwd: dir, encoding: "utf8" }).trim();
}
function commit(dir: string, message: string): string {
  git(dir, "add", "-A");
  git(dir, "commit", "--quiet", "-m", message);
  return git(dir, "rev-parse", "HEAD");
}
async function fixture(run: (dir: string, base: string) => Promise<void>, initial: Files = {}): Promise<void> {
  const dir = join(tmpdir(), `diffci-yarn-${randomUUID()}`);
  mkdirSync(dir, { recursive: true });
  try {
    git(dir, "init", "--quiet");
    git(dir, "config", "user.email", "t@diffci.local");
    git(dir, "config", "user.name", "t");
    git(dir, "config", "commit.gpgsign", "false");
    git(dir, "config", "core.autocrlf", "false");
    write(dir, { ...files, ...initial });
    await run(dir, commit(dir, "base"));
  } finally { rmSync(dir, { recursive: true, force: true }); }
}
async function changed(dir: string, base: string, change: Files) {
  write(dir, change);
  const head = commit(dir, "head");
  const delta = await analyzeGitDelta({ repoPath: dir, baseSha: base, headSha: head });
  assert.ok(delta.success);
  return { head, delta: delta.delta, result: await analyzeCheckout({ repoPath: dir, base, head }) };
}
function runTests(dir: string, selected: string[] = []) {
  // A child test runner must not inherit Node's marker for the currently executing test file.
  const env = { ...process.env };
  delete env.NODE_TEST_CONTEXT;
  const result = spawnSync(process.execPath, ["--test", ...selected], { cwd: dir, env, encoding: "utf8" });
  assert.equal(result.error, undefined);
  return result;
}
function install(dir: string, value: string, version: string) {
  // Synthetic installed packages exercise real Node peer resolution without a registry request.
  write(dir, {
    "node_modules/host/package.json": JSON.stringify({ name: "host", version, type: "module", exports: "./index.js" }),
    "node_modules/host/index.js": `export const value = ${JSON.stringify(value)};\n`,
    "node_modules/consumer/package.json": JSON.stringify({ name: "consumer", version: "1.0.0", type: "module", exports: "./index.js", peerDependencies: { host: "^1.0.0" } }),
    "node_modules/consumer/index.js": `export { value } from "host";\n`,
  });
}

describe("yarnLockAffectedDependencies", () => {
  it("returns every direct root for a direct change because Classic does not record peer edges", () => {
    assert.deepEqual(yarnLockAffectedDependencies(lock(), lock("1.0.1"), roots, roots), ["consumer", "host"]);
  });

  for (const field of ["dependencies", "optionalDependencies"]) {
    it(`includes every root for a transitive-only change through ${field}`, () => {
      const tree = (version: string) => header + entry("consumer") + entry("host", "1.0.0", "^1.0.0", `  ${field}:\n    leaf "^1.0.0"\n`) + entry("leaf", version);
      assert.deepEqual(yarnLockAffectedDependencies(tree("1.0.0"), tree("1.0.1"), roots, roots), ["consumer", "host"]);
    });
  }

  it("understands grouped quoted selectors and scoped package names", () => {
    const tree = (version: string) => header
      + entry("@scope/lib", version).replace('"@scope/lib@^1.0.0":', '"@scope/lib@^1.0.0", "@scope/lib@~1.0.0":')
      + entry("consumer", "1.0.0", "^1.0.0", '  dependencies:\n    "@scope/lib" "~1.0.0"\n');
    const direct = { "@scope/lib": "^1.0.0", consumer: "^1.0.0" };
    assert.deepEqual(yarnLockAffectedDependencies(tree("1.0.0"), tree("1.0.1"), direct, direct), ["@scope/lib", "consumer"]);
  });

  it("resolves exact descriptors when several versions share a package name", () => {
    const tree = (version: string) => header + entry("consumer", "1.0.0", "^1.0.0", '  dependencies:\n    host "^2.0.0"\n') + entry("host") + entry("host", version, "^2.0.0");
    assert.deepEqual(yarnLockAffectedDependencies(tree("2.0.0"), tree("2.0.1"), roots, roots), ["consumer", "host"]);
  });

  it("treats comments, entry order and line endings as a semantic no-op", () => {
    const after = (header + entry("host") + "# same packages\n" + entry("consumer")).replaceAll("\n", "\r\n");
    assert.deepEqual(yarnLockAffectedDependencies(lock(), after, roots, roots), []);
  });

  it("accepts generated bare selectors and a UTF-8 byte-order mark", () => {
    const before = "\uFEFF" + lock().replaceAll('"consumer@^1.0.0"', "consumer@^1.0.0").replaceAll('"host@^1.0.0"', "host@^1.0.0");
    assert.deepEqual(yarnLockAffectedDependencies(before, lock("1.0.1"), roots, roots), ["consumer", "host"]);
  });

  it("does not mistake integrity-only or resolved-only edits for a semantic no-op", () => {
    const firstIntegrity = `sha512-${Buffer.alloc(64, 1).toString("base64")}`;
    const nextIntegrity = `sha512-${Buffer.alloc(64, 2).toString("base64")}`;
    const before = lock().replace('  version "1.0.0"', `  version "1.0.0"\n  integrity ${firstIntegrity}`);
    assert.deepEqual(yarnLockAffectedDependencies(before, before.replace(firstIntegrity, nextIntegrity), roots, roots), ["consumer", "host"]);
    assert.deepEqual(yarnLockAffectedDependencies(lock(), lock().replace("#1111111111111111111111111111111111111111", "#2111111111111111111111111111111111111111"), roots, roots), ["consumer", "host"]);
  });

  it("requires a content pin even for an unchanged registry resolution", () => {
    const withoutPins = lock().replace(/#[a-f0-9]{40}/g, "");
    assert.equal(yarnLockAffectedDependencies(withoutPins, withoutPins, roots, roots), undefined);
    const integrity = `sha512-${Buffer.alloc(64, 1).toString("base64")}`;
    const withIntegrity = withoutPins.replaceAll('  version "1.0.0"', `  version "1.0.0"\n  integrity ${integrity}`);
    assert.deepEqual(yarnLockAffectedDependencies(withIntegrity, withIntegrity + "# unchanged\n", roots, roots), []);
  });

  it("validates both manifest sides, including a manifest bump without its selector", () => {
    assert.equal(yarnLockAffectedDependencies(lock(), lock("1.0.1"), { ...roots, host: "^2.0.0" }, roots), undefined);
    assert.equal(yarnLockAffectedDependencies(lock(), lock("1.0.1"), roots, { ...roots, host: "^2.0.0" }), undefined);
    assert.equal(yarnLockAffectedDependencies(lock(), lock(), roots, { ...roots, host: "^2.0.0" }), undefined);
  });

  it("accepts plain root records but refuses inherited dependency descriptors", () => {
    const plain = Object.assign(Object.create(null) as Record<string, string>, roots);
    assert.deepEqual(yarnLockAffectedDependencies(lock(), lock("1.0.1"), plain, plain), ["consumer", "host"]);
    const inherited = Object.create(roots) as Record<string, string>;
    assert.equal(yarnLockAffectedDependencies(lock(), lock("1.0.1"), inherited, roots), undefined);
    assert.equal(yarnLockAffectedDependencies(lock(), lock("1.0.1"), roots, inherited), undefined);
  });

  it("handles an attributed root addition or removal using both manifest sides", () => {
    const added = lock() + entry("new-root");
    const expanded = { ...roots, "new-root": "^1.0.0" };
    assert.deepEqual(yarnLockAffectedDependencies(lock(), added, roots, expanded), ["consumer", "host", "new-root"]);
    assert.deepEqual(yarnLockAffectedDependencies(added, lock(), expanded, roots), ["consumer", "host", "new-root"]);
  });

  it("handles dependency cycles without omitting the changed package", () => {
    const tree = (version: string) => header + entry("consumer")
      + entry("host", "1.0.0", "^1.0.0", '  dependencies:\n    leaf "^1.0.0"\n')
      + entry("leaf", version, "^1.0.0", '  dependencies:\n    host "^1.0.0"\n');
    assert.deepEqual(yarnLockAffectedDependencies(tree("1.0.0"), tree("1.0.1"), roots, roots), ["consumer", "host"]);
  });

  const unsupported: Array<[string, string | undefined]> = [
    ["missing contents", undefined],
    ["empty contents", ""],
    ["Berry metadata", "__metadata:\n  version: 8\n"],
    ["unclosed string", header + 'host@^1.0.0:\n  version "1.0.0\n'],
    ["duplicate selector", lock() + entry("host")],
    ["mixed package names in a selector group", header + entry("host").replace('"host@^1.0.0":', '"host@^1.0.0", "consumer@^1.0.0":')],
    ["invalid numeric prerelease", lock().replace('  version "1.0.0"', '  version "1.0.0-01"')],
    ["duplicate field", lock().replace('  version "1.0.0"', '  version "1.0.0"\n  version "1.0.1"')],
    ["unknown field", lock().replace('  version "1.0.0"', '  version "1.0.0"\n  unknown "value"')],
    ["missing resolved source", lock().replace(/^  resolved .*\n/m, "")],
    ["invalid indentation", lock().replace('  version "1.0.0"', ' version "1.0.0"')],
    ["merge conflict", lock() + "<<<<<<< HEAD\n=======\n>>>>>>> branch\n"],
    ["missing dependency edge", header + entry("consumer") + entry("host", "1.0.0", "^1.0.0", '  dependencies:\n    missing "^1.0.0"\n')],
    ["unreachable package", lock() + entry("orphan")],
    ["file protocol", lock().replaceAll("host@^1.0.0", "host@file:../host")],
    ["workspace protocol", lock().replaceAll("host@^1.0.0", "host@workspace:*")],
    ["npm alias", lock().replaceAll("host@^1.0.0", "host@npm:other@^1.0.0")],
    ["git source", lock().replace("https://registry.yarnpkg.com/consumer/-/consumer-1.0.0.tgz", "git+https://example.invalid/consumer.git")],
  ];
  for (const [name, content] of unsupported) {
    it(`falls back for ${name} on either side`, () => {
      assert.equal(yarnLockAffectedDependencies(content, lock(), roots, roots), undefined);
      assert.equal(yarnLockAffectedDependencies(lock(), content, roots, roots), undefined);
    });
  }
});

describe("Yarn Classic dependency changes end to end", () => {
  it("keeps a failing peer consumer in the public CLI selection and skips a dependency-free test", async () => {
    await fixture(async (dir, base) => {
      install(dir, "ready", "1.0.0");
      const baseline = runTests(dir);
      assert.equal(baseline.status, 0, baseline.stdout + baseline.stderr);
      assert.match(baseline.stdout, /tests 3/);
      install(dir, "changed", "1.0.1");
      const { head, delta, result } = await changed(dir, base, { "yarn.lock": lock("1.0.1") });
      assert.deepEqual(delta.analysis.changedDependencies, ["consumer", "host"]);
      assert.equal(delta.analysis.lockfileChanged, false);
      assert.equal(result.impact.fallbackRequired, false);
      assert.deepEqual(result.plan.selectedTests, ["src/consumer.test.js", "src/host.test.js"]);
      assert.ok(result.impact.riskSignals.some((signal) => signal.reason === "DEPENDENCY_MANIFEST"));
      const root = fileURLToPath(new URL("../../", import.meta.url));
      const cli = spawnSync(process.execPath, ["--import", "tsx", fileURLToPath(new URL("../../src/cli.ts", import.meta.url)), "plan", "--repo", dir, "--base", base, "--head", head], { cwd: root, encoding: "utf8" });
      assert.equal(cli.error, undefined);
      assert.equal(cli.status, 0, cli.stderr);
      const plan = JSON.parse(cli.stdout).plan as { selectedTests: string[] };
      assert.deepEqual(plan.selectedTests, result.plan.selectedTests);
      const hostOnly = runTests(dir, ["src/host.test.js"]);
      assert.equal(hostOnly.status, 0);
      assert.match(hostOnly.stdout, /tests 1/);
      const selected = runTests(dir, plan.selectedTests);
      assert.equal(selected.status, 1, selected.stdout + selected.stderr);
      assert.match(selected.stdout, /consumer expects the original peer behavior/);
      assert.match(selected.stdout, /fail 1/);
      assert.equal(runTests(dir).status, 1);
    });
  });

  it("covers raw lockfile readers even for a semantic no-op", async () => {
    await fixture(async (dir, base) => {
      const { delta, result } = await changed(dir, base, { "yarn.lock": lock() + "# regenerated\n" });
      assert.deepEqual(delta.analysis.changedDependencies, []);
      assert.equal(result.impact.fallbackRequired, false);
      assert.deepEqual(result.plan.selectedTests, ["src/lock.test.js"]);
    }, { "src/lock.test.js": `import test from "node:test";\nimport { readFileSync } from "node:fs";\ntest("lock reader", () => readFileSync("yarn.lock", "utf8"));\n` });
  });

  it("does not select dependency importers for a semantic no-op without lockfile readers", async () => {
    await fixture(async (dir, base) => {
      const { delta, result } = await changed(dir, base, { "yarn.lock": header + entry("host") + entry("consumer") });
      assert.deepEqual(delta.analysis.changedDependencies, []);
      assert.equal(result.impact.fallbackRequired, false);
      assert.deepEqual(result.plan.selectedTests, []);
    });
  });

  it("keeps full fallback when a discovered lockfile reader exceeds the content reader limit", async () => {
    await fixture(async (dir, base) => {
      const { delta, result } = await changed(dir, base, { "yarn.lock": lock() + "# regenerated\n" });
      assert.deepEqual(delta.analysis.changedDependencies, []);
      assert.equal(result.impact.fallbackRequired, true);
      assert.ok(result.plan.selectedTests.includes("src/lock.test.js"));
    }, { "src/lock.test.js": "/*" + "x".repeat(1_048_600) + '*/\nimport test from "node:test";\nimport { readFileSync } from "node:fs";\ntest("large lock reader", () => readFileSync("yarn.lock", "utf8"));\n' });
  });

  const unresolvedReaders: Array<[string, Files]> = [
    ["test script", { "package.json": manifest({ scripts: { test: "node --test && cat yarn.lock" } }) }],
    ["test-feeding workflow", { ".github/workflows/test.yml": "on: push\njobs:\n  test:\n    runs-on: ubuntu-latest\n    steps:\n      - run: cat yarn.lock\n      - run: node --test\n" }],
    ["implicit configuration", { "vitest.config.js": 'import { readFileSync } from "node:fs";\nexport default { value: readFileSync("yarn.lock", "utf8") };\n' }],
  ];
  for (const [name, initial] of unresolvedReaders) {
    it(`keeps full fallback when a ${name} reads the lockfile`, async () => {
      await fixture(async (dir, base) => {
        const { delta, result } = await changed(dir, base, { "yarn.lock": lock() + "# regenerated\n" });
        assert.deepEqual(delta.analysis.changedDependencies, []);
        assert.equal(result.impact.fallbackRequired, true);
        assert.ok(result.impact.fallbackReasons.some((reason) => /yarn\.lock/.test(reason)));
      }, initial);
    });
  }

  it("does not use an unrelated lock bump to validate an unmatched manifest descriptor", async () => {
    await fixture(async (dir, base) => {
      const { delta, result } = await changed(dir, base, {
        "package.json": manifest({ dependencies: { ...roots, host: "^2.0.0" } }),
        "yarn.lock": header + entry("consumer", "1.0.1") + entry("host"),
      });
      assert.equal(delta.analysis.lockfileChanged, true);
      assert.equal(result.impact.fallbackRequired, true);
      assert.ok(result.impact.fallbackReasons.some((reason) => /lockfile/i.test(reason)));
    });
  });

  it("narrows a matching manifest bump and retains tests that read package.json", async () => {
    await fixture(async (dir, base) => {
      const { delta, result } = await changed(dir, base, {
        "package.json": manifest({ dependencies: { ...roots, host: "^1.1.0" } }),
        "yarn.lock": header + entry("consumer") + entry("host", "1.1.0", "^1.1.0"),
      });
      assert.deepEqual(delta.analysis.changedDependencies, ["consumer", "host"]);
      assert.equal(delta.analysis.dependencyManifestChanged, false);
      assert.equal(result.impact.fallbackRequired, false);
      assert.deepEqual(result.plan.selectedTests, ["src/consumer.test.js", "src/host.test.js", "src/manifest.test.js"]);
    }, { "src/manifest.test.js": 'import test from "node:test";\nimport { readFileSync } from "node:fs";\ntest("manifest reader", () => readFileSync("package.json", "utf8"));\n' });
  });

  for (const [name, content] of [
    ["malformed", header + "host@^1.0.0:\n  version \"unfinished\n"],
    ["Berry", "__metadata:\n  version: 8\n\"host@npm:^1.0.0\":\n  version: 1.0.1\n"],
  ]) {
    it(`keeps full fallback for ${name} lockfiles`, async () => {
      await fixture(async (dir, base) => {
        const { delta, result } = await changed(dir, base, { "yarn.lock": content });
        assert.equal(delta.analysis.lockfileChanged, true);
        assert.equal(result.impact.fallbackRequired, true);
      });
    });
  }

  it("attributes a transitive-only bump while retaining both direct importers", async () => {
    const tree = (version: string) => header + entry("consumer") + entry("host", "1.0.0", "^1.0.0", '  dependencies:\n    leaf "^1.0.0"\n') + entry("leaf", version);
    await fixture(async (dir, base) => {
      const { delta, result } = await changed(dir, base, { "yarn.lock": tree("1.0.1") });
      assert.deepEqual(delta.analysis.changedDependencies, ["consumer", "host"]);
      assert.equal(result.impact.fallbackRequired, false);
      assert.deepEqual(result.plan.selectedTests, ["src/consumer.test.js", "src/host.test.js"]);
    }, { "yarn.lock": tree("1.0.0") });
  });

  it("keeps full fallback when repository code imports an undeclared hoisted dependency", async () => {
    const tree = (version: string) => header + entry("consumer") + entry("host", "1.0.0", "^1.0.0", '  dependencies:\n    leaf "^1.0.0"\n') + entry("leaf", version);
    await fixture(async (dir, base) => {
      const { result } = await changed(dir, base, { "yarn.lock": tree("1.0.1") });
      assert.equal(result.impact.fallbackRequired, true);
    }, { "yarn.lock": tree("1.0.0"), "src/hoisted.test.js": 'import test from "node:test";\nimport leaf from "leaf";\ntest("hoisted", () => leaf);\n' });
  });

  it("keeps full fallback for unimported tooling even when only a runtime package changed", async () => {
    await fixture(async (dir, base) => {
      const { delta, result } = await changed(dir, base, { "yarn.lock": lock("1.0.1") + entry("tooling") });
      assert.deepEqual(delta.analysis.changedDependencies, ["consumer", "host", "tooling"]);
      assert.equal(result.impact.fallbackRequired, true);
      assert.ok(result.impact.fallbackReasons.some((reason) => /tooling.*no repository source imports/.test(reason)));
    }, { "package.json": manifest({ devDependencies: { tooling: "^1.0.0" } }), "yarn.lock": lock() + entry("tooling") });
  });

  it("does not clear unrelated configuration changes", async () => {
    await fixture(async (dir, base) => {
      const { result } = await changed(dir, base, { "yarn.lock": lock("1.0.1"), "tsconfig.json": '{"compilerOptions":{"strict":false}}\n' });
      assert.equal(result.impact.fallbackRequired, true);
      assert.ok(result.impact.fallbackReasons.some((reason) => /configuration/i.test(reason)));
    }, { "tsconfig.json": '{"compilerOptions":{"strict":true}}\n' });
  });

  const guardedManifests: Array<[string, Record<string, unknown>]> = [
    ["workspaces", { workspaces: ["packages/*"] }],
    ["resolutions", { resolutions: { host: "1.0.0" } }],
    ["flat installs", { flat: true }],
    ["install configuration", { installConfig: { pnp: true } }],
    ["bundled dependencies", { bundledDependencies: ["host"] }],
    ["bundleDependencies alias", { bundleDependencies: ["host"] }],
    ["peer dependencies", { peerDependencies: { host: "^1.0.0" } }],
    ["conflicting direct descriptors", { devDependencies: { host: "^2.0.0" } }],
    ["non-string direct descriptor", { dependencies: { ...roots, host: 1 } }],
  ];
  for (const [name, fields] of guardedManifests) {
    it(`retains the global lock signal for ${name}`, async () => {
      await fixture(async (dir, base) => {
        const { delta, result } = await changed(dir, base, { "yarn.lock": lock("1.0.1") });
        assert.equal(delta.analysis.lockfileChanged, true);
        assert.equal(result.impact.fallbackRequired, true);
      }, { "package.json": manifest(fields) });
    });
  }

  for (const path of ["package-lock.json", "pnpm-lock.yaml", ".yarnrc", ".yarnrc.yml", ".pnp.cjs"]) {
    it(`does not narrow when ${path} is present and unchanged`, async () => {
      await fixture(async (dir, base) => {
        const { delta, result } = await changed(dir, base, { "yarn.lock": lock("1.0.1") });
        assert.equal(delta.analysis.lockfileChanged, true);
        assert.equal(result.impact.fallbackRequired, true);
      }, { [path]: path.endsWith(".json") ? "{}\n" : "# synthetic unsupported install configuration\n" });
    });
  }

  const structuralChanges: Array<[string, Files, Files]> = [
    ["added root lock", { "yarn.lock": undefined }, { "yarn.lock": lock("1.0.1") }],
    ["deleted root lock", {}, { "yarn.lock": undefined }],
    ["renamed root lock", {}, { "yarn.lock": undefined, "previous/yarn.lock": lock() }],
    ["nested lock", { "packages/web/yarn.lock": lock() }, { "yarn.lock": lock("1.0.1"), "packages/web/yarn.lock": lock("1.0.1") }],
    ["nested manifest", { "packages/web/package.json": '{"name":"web","version":"1.0.0"}\n' }, { "yarn.lock": lock("1.0.1"), "packages/web/package.json": '{"name":"web","version":"2.0.0"}\n' }],
    ["mixed lock changes", { "package-lock.json": "{}\n" }, { "yarn.lock": lock("1.0.1"), "package-lock.json": '{"lockfileVersion":3}\n' }],
  ];
  for (const [name, initial, change] of structuralChanges) {
    it(`retains full fallback for ${name}`, async () => {
      await fixture(async (dir, base) => {
        const { delta, result } = await changed(dir, base, change);
        assert.equal(delta.analysis.lockfileChanged, true);
        assert.equal(result.impact.fallbackRequired, true);
      }, initial);
    });
  }
});
